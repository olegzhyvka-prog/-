# Стеля виручки соло-виконавця: скільки одиниць фізично влазить у місяць.
# ВХІД-ПРИПУЩЕННЯ (оцінка, не факт): години на одиницю і доступні години/міс.
HOURS_PER_MONTH = [40, 80, 120]   # 10 / 20 / 30 год на тиждень на ДОСТАВКУ
SKUS = [
    # назва, ціна, годин на одиницю (оцінка), реклама з кишені виконавця
    ("Досьє $90",            90,   4,   0),
    ("Повний тест $290 (реклама включена)", 290, 12, 200),
    ("Повний тест $290 (реклама окремо)",   290, 12,   0),
    ("Потік $990/міс, 4 гіпотези",          990, 40,   0),
]
print(f"{'SKU':<40}{'год/од':>7}{'од/міс':>9}{'вал.виручка/міс':>18}{'мінус реклама':>16}")
for cap in HOURS_PER_MONTH:
    print("\n=== Доступно на доставку: %d год/міс ===" % cap)
    for name, price, hrs, ads in SKUS:
        units = cap / hrs
        rev = units * price
        net = units * (price - ads)
        print(f"{name:<40}{hrs:>7}{units:>9.1f}{rev:>18,.0f}{net:>16,.0f}")
